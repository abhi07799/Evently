CREATE TABLE tickets_tbl (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             ticket_status VARCHAR(50) NOT NULL,

                             ticket_stock_id BIGINT NOT NULL,
                             purchaser_user_id BIGINT NOT NULL,

                             qr_code_id UUID,

                             created_at TIMESTAMP NOT NULL,
                             updated_at TIMESTAMP NOT NULL,

                             CONSTRAINT fk_ticket_stock
                                 FOREIGN KEY (ticket_stock_id)
                                     REFERENCES tickets_stock_tbl(id),

                             CONSTRAINT fk_ticket_purchaser
                                 FOREIGN KEY (purchaser_user_id)
                                     REFERENCES users_tbl(id)
);