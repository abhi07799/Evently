CREATE TABLE events_tbl (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            event_name VARCHAR(255) NOT NULL ,
                            description TEXT NOT NULL ,
                            venue VARCHAR(255) NOT NULL ,

                            event_start_time TIMESTAMP NOT NULL ,
                            event_end_time TIMESTAMP NOT NULL ,

                            event_status VARCHAR(50) NOT NULL ,

                            ticket_sales_start_time TIMESTAMP NOT NULL ,
                            ticket_sales_end_time TIMESTAMP NOT NULL ,

                            organizer_user_id BIGINT NOT NULL ,
                            attendee_user_id BIGINT NOT NULL ,
                            staff_user_id BIGINT NOT NULL ,

                            created_at TIMESTAMP NOT NULL,
                            updated_at TIMESTAMP NOT NULL,

                            CONSTRAINT fk_event_organizer
                                FOREIGN KEY (organizer_user_id)
                                    REFERENCES users_tbl(id),

                            CONSTRAINT fk_event_attendee
                                FOREIGN KEY (attendee_user_id)
                                    REFERENCES users_tbl(id),

                            CONSTRAINT fk_event_staff
                                FOREIGN KEY (staff_user_id)
                                    REFERENCES users_tbl(id)
);